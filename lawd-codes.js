const norm = (v) => v.replace(/\s+/g, "");

/**
 * 일반구가 있는 시(수원시·성남시·화성시 등) 묶음: 시 코드(앞 4자리+0) → 하위 구 코드들.
 * 구 이름이 "OO시 OO구" 꼴인 행에서 자동으로 만든다.
 */
const CITY_GROUPS = (() => {
  const map = new Map();
  for (const row of LAWD_CODES) {
    const m = row.name.match(/^(\S+ \S+시) \S+구$/);
    if (!m) continue;
    const code = row.code.slice(0, 4) + "0";
    if (!map.has(code)) map.set(code, { code, name: m[1], codes: [] });
    map.get(code).codes.push(row.code);
  }
  return [...map.values()];
})();

const searchText = (row) =>
  `${row.name} ${SIDO_ALIASES[row.code.slice(0, 2)] ?? ""} ${ROW_ALIASES[row.code] ?? ""}`;

/**
 * 지역명(자유 텍스트) 또는 5자리 코드 → 조회할 LAWD_CD 배열.
 * - 5자리 숫자: 현재 코드면 그대로, 옛 코드면 새 코드로, 시 전체 코드(41110 등)면 하위 구 전부.
 * - 공백으로 나뉜 각 토큰이 모두 지역명(옛 시도 이름 포함)에 들어 있어야 매칭.
 * - "수원시"처럼 일반구가 있는 시만 주면 하위 구 코드를 모두 돌려준다.
 * - 완전 일치(공백 제거 기준)가 있으면 최우선.
 * - 후보가 여럿이면(예: "중구") 후보 목록과 함께 에러, 없으면 code.go.kr 안내와 함께 에러.
 */
export function resolveRegionCodes(input) {
  const s = String(input ?? "").trim();
  if (!s) throw new Error("지역명을 입력하세요 (예: '강남구', '성남시 분당구').");

  if (/^\d{5}$/.test(s)) {
    if (ABOLISHED[s]) throw new Error(`${s}: ${ABOLISHED[s]}`);
    if (LEGACY_CODES[s]) return [LEGACY_CODES[s]];
    const group = CITY_GROUPS.find((g) => g.code === s);
    if (group) return [...group.codes];
    return [s];
  }

  const tokens = s.split(/\s+/).filter(Boolean);
  const rowHits = LAWD_CODES.filter((row) => tokens.every((t) => searchText(row).includes(t)));
  const groupHits = CITY_GROUPS.filter((g) => {
    const text = `${g.name} ${SIDO_ALIASES[g.code.slice(0, 2)] ?? ""}`;
    return tokens.every((t) => text.includes(t));
  });

  // 시 묶음이 하나만 걸리고 나머지가 전부 그 시의 구라면 → 시 전체(하위 구 모두)
  if (groupHits.length === 1) {
    const g = groupHits[0];
    if (rowHits.every((r) => g.codes.includes(r.code))) return [...g.codes];
  }

  if (rowHits.length === 0 && groupHits.length === 0) {
    throw new Error(
      `"${s}" 에 해당하는 시군구를 찾지 못했습니다. ` +
        `읍/면/동 이름이 아니라 시/군/구 단위로 입력해보세요 (예: '수원시 영통구'). ` +
        `그래도 안 되면 https://www.code.go.kr/stdcode/regCodeL.do 에서 5자리 법정동코드를 직접 찾아 입력하세요.`
    );
  }

  const exact = rowHits.find((row) => norm(row.name) === norm(s));
  if (exact) return [exact.code];
  if (rowHits.length === 1 && groupHits.length === 0) return [rowHits[0].code];

  const cand = [
    ...groupHits.map((g) => `- ${g.name} 전체 (구 ${g.codes.length}곳 합산)`),
    ...rowHits.map((row) => `- ${row.name} (${row.code})`),
  ];
  throw new Error(
    `"${s}" 에 해당하는 시군구가 ${cand.length}곳 있어 특정할 수 없습니다. 더 구체적으로 입력하세요:\n${cand
      .slice(0, 20)
      .join("\n")}`
  );
}

/**
 * 지역명 → LAWD_CD 하나. 시 전체처럼 여러 구로 나뉘는 입력이면 구를 지정하라는 에러.
 * (서버는 여러 구를 합쳐 조회하는 resolveRegionCodes를 쓴다.)
 */
export function resolveRegion(input) {
  const codes = resolveRegionCodes(input);
  if (codes.length === 1) return codes[0];
  const names = codes.map((c) => `- ${LAWD_CODES.find((r) => r.code === c)?.name ?? c} (${c})`);
  throw new Error(`"${input}" 은(는) 구 ${codes.length}곳으로 나뉩니다. 구를 지정하세요:\n${names.join("\n")}`);
}
